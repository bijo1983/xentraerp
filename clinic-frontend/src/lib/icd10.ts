export function searchIcd(q: string, limit = 8): [string, string][] {
  const s = q.trim().toLowerCase()
  if (!s) return COMMON_ICD10.slice(0, limit)
  return COMMON_ICD10.filter(([c, d]) => c.toLowerCase().startsWith(s) || d.toLowerCase().includes(s)).slice(0, limit)
}
